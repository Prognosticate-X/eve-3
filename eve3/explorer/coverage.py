"""Coverage: Task Diversity Tracking, Anti-Collapse Guardrails, and Metamorphic Testing.

Implements Phase 7 Exploration Guards:
1. Feature vectorization and semantic cluster entropy H(C) over task space.
2. Anti-collapse guardrails:
   - Synthetic task ratio capped at <= 60%.
   - Trigger recovery (anchor injection & temperature boost) when entropy degrades.
3. Metamorphic Testing & Blindspot Verification:
   - Validates boundary and algebraic properties (involution, monotonicity, empty-list safety)
     on synthesized programs to detect validator reward hacking or shortcut fits.
"""

from dataclasses import dataclass, field
import math
from typing import Any, Callable, Dict, List, Optional, Tuple

from eve3.dsl.interpreter import DSLInterpreter
from eve3.models import CandidateProgram, Task


@dataclass
class CoverageConfig:
    """Configuration for coverage monitoring and anti-collapse guardrails."""
    max_synthetic_ratio: float = 0.60      # Maximum allowable synthetic task fraction
    min_coverage_entropy: float = 0.40     # Normalized entropy threshold below which collapse triggers
    num_clusters: int = 8                  # Number of semantic task bins / clusters
    window_size: int = 25                  # Sliding window size for coverage calculation


@dataclass
class GuardrailStatus:
    """Report generated by CoverageGuard evaluating diversity and distribution health."""
    passed: bool
    synthetic_ratio: float
    coverage_entropy: float
    collapse_detected: bool
    recommended_action: str  # "ok", "boost_anchor_injection", "boost_temperature"
    details: Dict[str, Any] = field(default_factory=dict)


class CoverageGuard:
    """Monitors task space diversity, enforces synthetic caps, and prevents mode collapse."""

    def __init__(self, config: Optional[CoverageConfig] = None):
        self.config = config or CoverageConfig()
        self.history: List[Task] = []

    def record_task(self, task: Task):
        """Append task to rolling history window."""
        self.history.append(task)
        if len(self.history) > self.config.window_size * 2:
            self.history.pop(0)

    def extract_task_features(self, task: Task) -> List[float]:
        """Extract standardized multi-dimensional feature vector from task."""
        all_inputs = [ex.get("input", []) for ex in task.visible_examples + task.hidden_tests]
        all_outputs = [ex.get("output", None) for ex in task.visible_examples + task.hidden_tests]

        # f0: Average input list length
        lengths = [len(inp) for inp in all_inputs if isinstance(inp, list)]
        f0 = (sum(lengths) / len(lengths)) if lengths else 0.0

        # f1: Min input value
        flat_inps = [x for inp in all_inputs if isinstance(inp, list) for x in inp]
        f1 = float(min(flat_inps)) if flat_inps else 0.0

        # f2: Max input value
        f2 = float(max(flat_inps)) if flat_inps else 0.0

        # f3: Output type (0.0 for list, 1.0 for scalar/int)
        f3 = 1.0 if any(isinstance(out, int) for out in all_outputs) else 0.0

        # f4: Task family index
        family_map = {
            "list_mapping": 0,
            "list_filtering": 1,
            "list_reduction": 2,
            "list_structural": 3,
            "list_composition": 4,
        }
        f4 = float(family_map.get(task.task_family, 5))

        # f5: Complexity estimate (AST depth if available or inferred)
        f5 = float(task.metadata.get("ast_depth", 2.0))

        return [f0, f1, f2, f3, f4, f5]

    def assign_cluster(self, features: List[float]) -> int:
        """Map feature vector to semantic discrete cluster index [0 .. num_clusters - 1]."""
        f0, f1, f2, f3, f4, f5 = features
        # Hash combination of output type (f3), family (f4), and complexity/length
        cluster_id = int((f3 * 4 + f4 * 2 + (1 if f0 > 3 else 0)) % self.config.num_clusters)
        return cluster_id

    def compute_clustering_entropy(self, tasks: Optional[List[Task]] = None) -> float:
        """Compute normalized Shannon clustering entropy H_norm in [0.0, 1.0]."""
        sample_tasks = tasks if tasks is not None else self.history[-self.config.window_size:]
        if len(sample_tasks) < 2:
            return 1.0  # Default uncollapsed prior

        cluster_counts = [0] * self.config.num_clusters
        for t in sample_tasks:
            feat = self.extract_task_features(t)
            c = self.assign_cluster(feat)
            cluster_counts[c] += 1

        total = len(sample_tasks)
        h = 0.0
        for count in cluster_counts:
            if count > 0:
                p = count / total
                h -= p * math.log(p)

        max_h = math.log(self.config.num_clusters)
        normalized_h = h / max_h if max_h > 0 else 0.0
        return float(min(1.0, max(0.0, normalized_h)))

    def check_guardrails(self, candidate_tasks: Optional[List[Task]] = None) -> GuardrailStatus:
        """Evaluate synthetic ratio and coverage entropy against pre-registered safety limits."""
        eval_tasks = candidate_tasks if candidate_tasks is not None else self.history[-self.config.window_size:]
        if not eval_tasks:
            return GuardrailStatus(
                passed=True,
                synthetic_ratio=0.0,
                coverage_entropy=1.0,
                collapse_detected=False,
                recommended_action="ok",
            )

        synth_count = sum(1 for t in eval_tasks if t.source in ("mutation", "decomposition", "synthetic"))
        total_count = len(eval_tasks)
        synthetic_ratio = synth_count / total_count

        entropy = self.compute_clustering_entropy(eval_tasks)
        collapse_detected = entropy < self.config.min_coverage_entropy

        reasons = []
        action = "ok"

        if synthetic_ratio > self.config.max_synthetic_ratio + 1e-6:
            reasons.append(f"Synthetic ratio {synthetic_ratio:.2f} exceeds cap {self.config.max_synthetic_ratio:.2f}")
            action = "boost_anchor_injection"

        if collapse_detected:
            reasons.append(f"Coverage entropy {entropy:.3f} is below collapse threshold {self.config.min_coverage_entropy:.3f}")
            if action == "ok":
                action = "boost_temperature"

        passed = len(reasons) == 0

        return GuardrailStatus(
            passed=passed,
            synthetic_ratio=synthetic_ratio,
            coverage_entropy=entropy,
            collapse_detected=collapse_detected,
            recommended_action=action,
            details={"violations": reasons, "task_count": total_count},
        )


class MetamorphicValidator:
    """Performs property-based metamorphic checks to prevent validator blindspot exploitation."""

    def __init__(self):
        self.interpreter = DSLInterpreter()

    def validate_program_blindspots(
        self,
        program: CandidateProgram,
        task: Task,
        timeout: float = 0.5,
    ) -> Tuple[bool, Optional[str]]:
        """Validate candidate program against algebraic and boundary invariants."""
        family = task.task_family

        try:
            # Invariant 1: Empty list boundary test
            # Functional list operations should never crash or return None on empty lists
            empty_res = self.interpreter.run(program.ast, [], timeout_seconds=timeout)
            if family in ("list_mapping", "list_filtering", "list_structural"):
                if empty_res != []:
                    return False, f"Empty list invariant violated: returned {empty_res!r} instead of []"
            elif family == "list_reduction":
                if empty_res not in (0, None):
                    return False, f"Empty list reduction invariant violated: returned {empty_res!r}"

            # Invariant 2: Extreme value tolerance
            # Program should safely handle negative and large integers without overflow
            large_input = [100, -100, 0]
            large_res = self.interpreter.run(program.ast, large_input, timeout_seconds=timeout)
            if large_res is None:
                return False, "Failed on extreme value test [100, -100, 0]"

            # Invariant 3: Idempotence / Involution for structural tasks
            if family == "list_structural" and "reverse" in program.code_str:
                test_inp = [1, 2, 3, 4]
                once = self.interpreter.run(program.ast, test_inp, timeout_seconds=timeout)
                twice = self.interpreter.run(program.ast, once, timeout_seconds=timeout)
                if twice != test_inp:
                    return False, f"Involution invariant violated: reverse(reverse(x)) != x, got {twice} vs {test_inp}"

            # Invariant 4: Monotonicity & Sub-length for filtering tasks
            if family == "list_filtering":
                test_inp = [-5, 0, 5, 10, -2, 8]
                res = self.interpreter.run(program.ast, test_inp, timeout_seconds=timeout)
                if not isinstance(res, list):
                    return False, f"Filtering must return a list, got {type(res)}"
                if len(res) > len(test_inp):
                    return False, f"Filtering output length {len(res)} exceeds input length {len(test_inp)}"
                for x in res:
                    if x not in test_inp:
                        return False, f"Filtered element {x} was not present in original input {test_inp}"

            # Invariant 5: Preservation of size for mapping tasks
            if family == "list_mapping":
                test_inp = [3, 7, 11]
                res = self.interpreter.run(program.ast, test_inp, timeout_seconds=timeout)
                if not isinstance(res, list) or len(res) != len(test_inp):
                    return False, f"Mapping invariant violated: output length {len(res) if isinstance(res, list) else 0} != input length {len(test_inp)}"

            return True, None

        except Exception as e:
            return False, f"Execution error during metamorphic testing: {str(e)}"
